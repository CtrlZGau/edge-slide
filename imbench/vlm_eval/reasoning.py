"""Extract the model's reasoning summaries from saved raw responses into readable markdown.

OpenAI does not return raw chain-of-thought: reasoning items carry an empty `content`, an
opaque `encrypted_content`, and (when requested) a `summary`. Only the summaries and the
reasoning-token counts are recoverable.

    python -m imbench.vlm_eval.reasoning runs/gpt-6-astra/edge-slide   # backfill all samples
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def summaries(raw: dict) -> list[str]:
    out = []
    for item in raw.get("output", []) or []:
        if item.get("type") == "reasoning":
            out += [s.get("text", "") for s in item.get("summary") or [] if s.get("text")]
    return out


def to_markdown(raws: list[dict], stage: int) -> str:
    L = [f"# Stage {stage} reasoning summaries",
         "", "_Summaries generated by the API. Raw thinking is encrypted and not available._", ""]
    for k, raw in enumerate(raws, 1):
        u = (raw.get("usage") or {})
        rt = (u.get("output_tokens_details") or {}).get("reasoning_tokens", "?")
        L += [f"## Attempt {k}  (reasoning tokens: {rt}, output tokens: {u.get('output_tokens', '?')})", ""]
        s = summaries(raw)
        L += ([t + "\n" for t in s] if s else ["_(no summary returned)_"])
        L.append("")
    return "\n".join(L)


def write_sample(d: Path) -> None:
    for stage in (1, 2):
        p = d / f"stage{stage}_raw.json"
        if p.exists():
            raws = json.loads(p.read_text())
            if raws:
                (d / f"stage{stage}_reasoning.md").write_text(to_markdown(raws, stage))


if __name__ == "__main__":
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "runs/gpt-6-astra/edge-slide")
    for d in sorted(root.glob("seed_*/**/sample_*")):
        write_sample(d)
        print("wrote", d)
